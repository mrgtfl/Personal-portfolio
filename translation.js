/* ==========================================================
   REVERSE TRANSLATIONS - FRENCH TO ENGLISH
   ========================================================== */

const reverseTextTranslations = Object.fromEntries(
    Object.entries(textTranslations).map(([english, french]) => [
        french,
        english
    ])
);


/* ==========================================================
   TRANSLATION FUNCTIONS
   ========================================================== */

function translateText(value, language) {
    const dictionary = language === "fr"
        ? textTranslations
        : reverseTextTranslations;

    return Object.entries(dictionary)
        .sort(([left], [right]) => right.length - left.length)
        .reduce(
            (translatedValue, [source, target]) =>
                translatedValue.replaceAll(source, target),
            value
        );
}


function translateDocument(language) {
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );

    const textNodes = [];

    while (walker.nextNode()) {
        textNodes.push(walker.currentNode);
    }

    textNodes.forEach(node => {
        if (node.parentElement?.closest("script, style")) {
            return;
        }

        node.nodeValue = translateText(node.nodeValue, language);
    });

    document.querySelectorAll("[data-details]").forEach(element => {
        element.dataset.details = translateText(
            element.dataset.details,
            language
        );
    });

    document.querySelectorAll("[title], [aria-label], [alt]").forEach(element => {
        ["title", "aria-label", "alt"].forEach(attribute => {
            if (element.hasAttribute(attribute)) {
                element.setAttribute(
                    attribute,
                    translateText(element.getAttribute(attribute), language)
                );
            }
        });
    });
}
